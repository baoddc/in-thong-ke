-- T-045 / D-018: giữ chỗ số phiếu TK 5 phút. Không sửa migration cũ; dán vào SQL Editor chạy lại được.
begin;

-- ---------- 1. Bảng tk_reservations ----------
create table if not exists public.tk_reservations (
  id bigint generated by default as identity primary key,
  tk_year int not null,
  tk_month int not null check (tk_month between 1 and 12),
  tk_seq int not null check (tk_seq between 1 and 999),
  user_id uuid not null default auth.uid()
    constraint tk_reservations_user_id_fkey references auth.users(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tk_reservations_ym_seq_uq unique (tk_year, tk_month, tk_seq),
  constraint tk_reservations_user_uq unique (user_id)  -- mỗi người giữ tối đa 1 số; cũng là index cho khóa ngoại
);

drop trigger if exists tk_reservations_set_updated_at on public.tk_reservations;
create trigger tk_reservations_set_updated_at before update on public.tk_reservations
  for each row execute function public.set_updated_at();

alter table public.tk_reservations enable row level security;
revoke all on public.tk_reservations from anon, authenticated;
grant select, delete on public.tk_reservations to authenticated;

-- Chỉ đọc/xóa dòng của mình; thêm/sửa chỉ qua RPC security definer (reserve_tk_number).
drop policy if exists tk_reservations_select on public.tk_reservations;
drop policy if exists tk_reservations_delete on public.tk_reservations;
create policy tk_reservations_select on public.tk_reservations for select to authenticated
  using (user_id = (select auth.uid()));
create policy tk_reservations_delete on public.tk_reservations for delete to authenticated
  using (user_id = (select auth.uid()));

-- ---------- 2. tk_next_seq: né chỗ giữ còn hạn của người khác ----------
-- security definer để đọc tk_reservations/transport_plans bất kể RLS; chỉ trả một số nguyên nên không lộ dữ liệu.
create or replace function public.tk_next_seq(p_year int, p_month int)
returns int language sql stable security definer set search_path = '' as $$
  select s from generate_series(1, 999) s
  where not exists (select 1 from public.transport_plans t
                    where t.tk_year = p_year and t.tk_month = p_month and t.tk_seq = s)
    and not exists (select 1 from public.tk_reservations r
                    where r.tk_year = p_year and r.tk_month = p_month and r.tk_seq = s
                      and r.expires_at > now() and r.user_id is distinct from (select auth.uid()))
  order by s limit 1
$$;

-- ---------- 3. reserve_tk_number / release_tk_reservation ----------
create or replace function public.reserve_tk_number()
returns text language plpgsql security definer set search_path = '' as $$
declare
  v_now timestamp := now() at time zone 'Asia/Ho_Chi_Minh';
  v_y int := extract(year from v_now)::int;
  v_m int := extract(month from v_now)::int;
  v_uid uuid := (select auth.uid());
  v_seq int;
begin
  if not public.is_active_user() then
    raise exception 'Bạn không có quyền giữ số phiếu thống kê' using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(hashtext('tk_number'));
  delete from public.tk_reservations where expires_at <= now();

  -- đang giữ số còn hạn cùng tháng và số chưa bị dùng → gia hạn, trả đúng số đó
  update public.tk_reservations r set expires_at = now() + interval '5 minutes'
  where r.user_id = v_uid and r.tk_year = v_y and r.tk_month = v_m
    and not exists (select 1 from public.transport_plans t
                    where t.tk_year = r.tk_year and t.tk_month = r.tk_month and t.tk_seq = r.tk_seq)
  returning r.tk_seq into v_seq;
  if found then
    return public.tk_format(v_y, v_m, v_seq);
  end if;

  delete from public.tk_reservations where user_id = v_uid;
  v_seq := public.tk_next_seq(v_y, v_m);
  if v_seq is null then
    raise exception 'Đã hết số phiếu thống kê trong tháng %/%', v_m, v_y using errcode = 'P0001';
  end if;

  insert into public.tk_reservations (tk_year, tk_month, tk_seq, user_id, expires_at)
  values (v_y, v_m, v_seq, v_uid, now() + interval '5 minutes');
  return public.tk_format(v_y, v_m, v_seq);
end $$;

create or replace function public.release_tk_reservation()
returns void language sql security definer set search_path = '' as $$
  delete from public.tk_reservations where user_id = (select auth.uid())
$$;

revoke execute on function public.reserve_tk_number(), public.release_tk_reservation() from public, anon;
grant execute on function public.reserve_tk_number(), public.release_tk_reservation() to authenticated;

-- ---------- 4. create_transport_plan: dùng số đang giữ (security invoker như cũ) ----------
-- Chữ ký và logic như migration 000003; thêm: dùng chỗ giữ của người gọi nếu còn hạn, và xóa chỗ giữ sau khi lưu.
create or replace function public.create_transport_plan(
  p_export_date date, p_transport_order_no text, p_transport_type_id bigint, p_vehicle_id bigint,
  p_driver_id bigint, p_fg_exporter_id bigint, p_material_exporter_ids bigint[], p_note text)
returns public.transport_plans language plpgsql set search_path = '' as $$
declare
  v_now timestamp := now() at time zone 'Asia/Ho_Chi_Minh';
  v_y int := extract(year from v_now)::int;
  v_m int := extract(month from v_now)::int;
  v_seq int;
  v_row public.transport_plans;
begin
  perform pg_advisory_xact_lock(hashtext('tk_number'));

  select r.tk_seq into v_seq from public.tk_reservations r
  where r.user_id = (select auth.uid()) and r.expires_at > now() and r.tk_year = v_y and r.tk_month = v_m
    and not exists (select 1 from public.transport_plans t
                    where t.tk_year = r.tk_year and t.tk_month = r.tk_month and t.tk_seq = r.tk_seq);
  if v_seq is null then
    v_seq := public.tk_next_seq(v_y, v_m);
  end if;
  if v_seq is null then
    raise exception 'Đã hết số phiếu thống kê trong tháng %/%', v_m, v_y using errcode = 'P0001';
  end if;

  insert into public.transport_plans (tk_number, tk_year, tk_month, tk_seq, export_date, transport_order_no,
    transport_type_id, vehicle_id, driver_id, fg_exporter_id, note)
  values (public.tk_format(v_y, v_m, v_seq), v_y, v_m, v_seq, p_export_date, nullif(btrim(p_transport_order_no), ''),
    p_transport_type_id, p_vehicle_id, p_driver_id, p_fg_exporter_id, nullif(btrim(p_note), ''))
  returning * into v_row;

  -- bỏ null, bỏ trùng (giữ lần xuất hiện đầu), sort_order = thứ tự còn lại bắt đầu từ 0
  insert into public.transport_plan_material_exporters (plan_id, lookup_id, sort_order)
  select v_row.id, s.x, (row_number() over (order by s.o) - 1)::int
  from (select t.x, min(t.o) as o
        from unnest(coalesce(p_material_exporter_ids, '{}')) with ordinality as t(x, o)
        where t.x is not null group by t.x) s;

  delete from public.tk_reservations where user_id = (select auth.uid());

  return v_row;
end $$;

revoke execute on function
  public.create_transport_plan(date,text,bigint,bigint,bigint,bigint,bigint[],text),
  public.tk_next_seq(int,int)
  from public, anon;
grant execute on function
  public.create_transport_plan(date,text,bigint,bigint,bigint,bigint,bigint[],text),
  public.tk_next_seq(int,int)
  to authenticated;

-- ---------- 5. Kiểm tra (chạy dưới postgres: auth.uid() null) ----------
do $$
declare
  v_uid uuid;
begin
  assert exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
                 where n.nspname = 'public' and c.relname = 'tk_reservations' and c.relrowsecurity), 'tk_reservations chưa bật RLS';
  assert (select count(*) from pg_policies where schemaname = 'public' and tablename = 'tk_reservations') = 2, 'tk_reservations: sai số policy';
  assert (select prosecdef from pg_proc where oid = 'public.tk_next_seq(int,int)'::regprocedure), 'tk_next_seq phải security definer';
  assert (select prosecdef from pg_proc where oid = 'public.reserve_tk_number()'::regprocedure), 'reserve_tk_number phải security definer';
  assert (select prosecdef from pg_proc where oid = 'public.release_tk_reservation()'::regprocedure), 'release_tk_reservation phải security definer';
  assert not (select prosecdef from pg_proc
              where oid = 'public.create_transport_plan(date,text,bigint,bigint,bigint,bigint,bigint[],text)'::regprocedure),
    'create_transport_plan phải security invoker';
  assert not has_function_privilege('anon', 'public.reserve_tk_number()', 'execute'), 'anon không được gọi reserve_tk_number';
  assert has_function_privilege('authenticated', 'public.reserve_tk_number()', 'execute'), 'authenticated phải gọi được reserve_tk_number';
  assert public.tk_next_seq(1999, 1) = 1, 'tk_next_seq tháng trống phải = 1';

  -- kịch bản: người khác giữ số 1 còn hạn → né; hết hạn → lấy lại (rollback bằng delete cuối)
  select u.id into v_uid from auth.users u
  where not exists (select 1 from public.tk_reservations r where r.user_id = u.id) limit 1;
  if v_uid is not null then
    insert into public.tk_reservations (tk_year, tk_month, tk_seq, user_id, expires_at)
    values (1999, 1, 1, v_uid, now() + interval '5 minutes');
    assert public.tk_next_seq(1999, 1) = 2, 'phải né số đang bị giữ';
    update public.tk_reservations set expires_at = now() - interval '1 second' where user_id = v_uid;
    assert public.tk_next_seq(1999, 1) = 1, 'chỗ giữ hết hạn phải coi như không có';
    delete from public.tk_reservations where tk_year = 1999 and user_id = v_uid;
  end if;
end $$;

commit;
