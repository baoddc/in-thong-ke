-- T-028 / D-012: chịu tải 500.000 - vài triệu dòng.
-- (1) RPC tìm kiếm phía server, (2) bảng tổng hợp inspection_daily_stats + trigger + RPC thống kê, (3) index phân trang.
-- Viết để chạy lại được khi dán vào SQL Editor: if not exists / or replace / drop if exists. Không xóa dữ liệu gốc.
-- Yêu cầu PostgreSQL 15+ (unique nulls not distinct). Cần pg_trgm (đã có từ 000006).
begin;

-- ---------- 1. Index phân trang / sắp xếp ổn định ----------
-- Đã có từ trước (không tạo lại): inspection_details(construction_id), (receiving_unit_id), (plan_id), (export_type_id), (product_id).
create index if not exists transport_plans_created_at_id_idx on public.transport_plans (created_at desc, id desc);
create index if not exists transport_plans_export_date_id_idx on public.transport_plans (export_date desc, id desc);
create index if not exists inspection_details_created_at_id_idx on public.inspection_details (created_at desc, id desc);
create index if not exists inspection_details_export_date_id_idx on public.inspection_details (export_date desc, id desc);
-- danh mục: liệt kê theo loại, sắp theo tên (search_lookup_items khi ô tìm trống)
create index if not exists lookup_items_kind_name_id_idx on public.lookup_items (kind, name, id);

-- ---------- 2. RPC tìm kiếm ----------
-- Từ khóa >= 3 ký tự: ilike '%x%' qua GIN trigram, khớp đầu chuỗi xếp trước, rồi mới nhất. Rỗng: 20 phiếu mới nhất.
-- Từ khóa 1-2 ký tự (trigram không dùng được): chỉ khớp đầu chuỗi, duyệt từ phiếu mới nhất.
create or replace function public.search_plan_numbers(p_q text, p_limit int default 20)
returns table(id bigint, tk_number text, export_date date)
language sql stable security invoker set search_path = ''
as $$
  with k as (
    select btrim(coalesce(p_q, '')) as q,
           replace(replace(replace(btrim(coalesce(p_q, '')), '\', '\\'), '%', '\%'), '_', '\_') as e,
           least(greatest(coalesce(p_limit, 20), 1), 50) as n
  )
  select r.id, r.tk_number, r.export_date
  from k
  cross join lateral (
    (select p.id, p.tk_number, p.export_date, p.created_at, 0 as rk
       from public.transport_plans p
      where char_length(k.q) < 3 and (k.q = '' or p.tk_number ilike k.e || '%')
      order by p.created_at desc, p.id desc
      limit k.n)
    union all
    (select p.id, p.tk_number, p.export_date, p.created_at,
            case when p.tk_number ilike k.e || '%' then 0 else 1 end as rk
       from public.transport_plans p
      where char_length(k.q) >= 3 and p.tk_number ilike '%' || k.e || '%'
      order by rk, p.created_at desc, p.id desc
      limit k.n)
  ) r
  order by r.rk, r.created_at desc, r.id desc
$$;

-- Khớp name hoặc code (công trình). Rỗng: n mục đầu theo tên. Khớp đầu chuỗi xếp trước, rồi theo tên.
create or replace function public.search_lookup_items(p_kind text, p_q text, p_limit int default 20)
returns setof public.lookup_items
language sql stable security invoker set search_path = ''
as $$
  with k as (
    select btrim(coalesce(p_q, '')) as q,
           replace(replace(replace(btrim(coalesce(p_q, '')), '\', '\\'), '%', '\%'), '_', '\_') as e,
           least(greatest(coalesce(p_limit, 20), 1), 50) as n
  )
  select (r.i).*
  from k
  cross join lateral (
    (select i as i, 0 as rk
       from public.lookup_items i
      where k.q = '' and i.kind = p_kind
      order by i.name, i.id
      limit k.n)
    union all
    (select i as i,
            case when i.name ilike k.e || '%' or i.code ilike k.e || '%' then 0 else 1 end as rk
       from public.lookup_items i
      where k.q <> '' and i.kind = p_kind
        and (i.name ilike '%' || k.e || '%' or i.code ilike '%' || k.e || '%')
      order by rk, i.name, i.id
      limit k.n)
  ) r
  order by r.rk, (r.i).name, (r.i).id
$$;

-- Lấy các mục theo id (hiển thị tên các id đang chọn khi sửa); tối đa 1000 mục.
create or replace function public.get_lookup_items(p_ids bigint[])
returns setof public.lookup_items
language sql stable security invoker set search_path = ''
as $$
  select * from public.lookup_items where id = any(p_ids) order by id limit 1000
$$;

revoke all on function public.search_plan_numbers(text,int), public.search_lookup_items(text,text,int),
  public.get_lookup_items(bigint[]) from public, anon;
grant execute on function public.search_plan_numbers(text,int), public.search_lookup_items(text,text,int),
  public.get_lookup_items(bigint[]) to authenticated;

-- ---------- 3. Bảng tổng hợp ----------
-- Không có khóa ngoại: đây là dữ liệu dẫn xuất; xóa mục danh mục chỉ bị chặn bởi inspection_details (restrict).
-- updated_at do upsert đặt (now()), không cần trigger set_updated_at. Dòng có row_count = 0 được giữ lại (vô hại).
create table if not exists public.inspection_daily_stats (
  id bigint generated by default as identity primary key,
  export_date date,
  export_type_id bigint,
  product_id bigint,
  row_count bigint not null default 0,
  quantity_sum numeric not null default 0,
  weight_kg_sum numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint inspection_daily_stats_key_uq unique nulls not distinct (export_date, export_type_id, product_id)
);

alter table public.inspection_daily_stats enable row level security;
revoke all on public.inspection_daily_stats from anon, authenticated;
grant select on public.inspection_daily_stats to authenticated;
drop policy if exists inspection_daily_stats_select on public.inspection_daily_stats;
create policy inspection_daily_stats_select on public.inspection_daily_stats
  for select to authenticated using ((select auth.uid()) is not null);
-- cố ý không có policy insert/update/delete: chỉ trigger (security definer) ghi được.

-- ---------- 4. Trigger cập nhật bảng tổng hợp (statement-level, transition tables) ----------
-- Cộng delta theo nhóm: INSERT +new, DELETE -old, UPDATE +new và -old. Một câu upsert cho cả lô nên nạp hàng loạt vẫn nhanh.
-- order by 1,2,3 để các giao dịch song song khóa dòng cùng thứ tự (giảm deadlock).
create or replace function public.inspection_stats_apply()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op in ('INSERT', 'UPDATE') then
    insert into public.inspection_daily_stats as t
      (export_date, export_type_id, product_id, row_count, quantity_sum, weight_kg_sum)
    select n.export_date, n.export_type_id, n.product_id,
           count(*), coalesce(sum(n.quantity), 0), coalesce(sum(n.total_weight_kg), 0)
    from new_rows n
    group by 1, 2, 3
    order by 1, 2, 3
    on conflict (export_date, export_type_id, product_id) do update set
      row_count = t.row_count + excluded.row_count,
      quantity_sum = t.quantity_sum + excluded.quantity_sum,
      weight_kg_sum = t.weight_kg_sum + excluded.weight_kg_sum,
      updated_at = now();
  end if;
  if tg_op in ('UPDATE', 'DELETE') then
    insert into public.inspection_daily_stats as t
      (export_date, export_type_id, product_id, row_count, quantity_sum, weight_kg_sum)
    select o.export_date, o.export_type_id, o.product_id,
           -count(*), -coalesce(sum(o.quantity), 0), -coalesce(sum(o.total_weight_kg), 0)
    from old_rows o
    group by 1, 2, 3
    order by 1, 2, 3
    on conflict (export_date, export_type_id, product_id) do update set
      row_count = t.row_count + excluded.row_count,
      quantity_sum = t.quantity_sum + excluded.quantity_sum,
      weight_kg_sum = t.weight_kg_sum + excluded.weight_kg_sum,
      updated_at = now();
  end if;
  return null;
end $$;

-- TRUNCATE không chạy trigger theo dòng: xóa luôn bảng tổng hợp để không lệch.
create or replace function public.inspection_stats_on_truncate()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  delete from public.inspection_daily_stats where true;
  return null;
end $$;

revoke all on function public.inspection_stats_apply(), public.inspection_stats_on_truncate()
  from public, anon, authenticated;

drop trigger if exists inspection_details_stats_ins on public.inspection_details;
drop trigger if exists inspection_details_stats_upd on public.inspection_details;
drop trigger if exists inspection_details_stats_del on public.inspection_details;
drop trigger if exists inspection_details_stats_trunc on public.inspection_details;
create trigger inspection_details_stats_ins after insert on public.inspection_details
  referencing new table as new_rows for each statement execute function public.inspection_stats_apply();
create trigger inspection_details_stats_upd after update on public.inspection_details
  referencing old table as old_rows new table as new_rows for each statement execute function public.inspection_stats_apply();
create trigger inspection_details_stats_del after delete on public.inspection_details
  referencing old table as old_rows for each statement execute function public.inspection_stats_apply();
create trigger inspection_details_stats_trunc before truncate on public.inspection_details
  for each statement execute function public.inspection_stats_on_truncate();

-- ---------- 5. Tính lại toàn bộ (backfill + sửa lệch khi cần) ----------
-- Khóa ghi trên inspection_details trong lúc tính (đọc vẫn được) rồi thay toàn bộ bảng tổng hợp trong một giao dịch:
-- chạy lại bao nhiêu lần cũng cho cùng kết quả, không đua với trigger. Chỉ postgres/Dashboard gọi được.
create or replace function public.rebuild_inspection_daily_stats()
returns bigint language plpgsql security definer set search_path = '' as $$
declare v bigint;
begin
  lock table public.inspection_details in share row exclusive mode;
  delete from public.inspection_daily_stats where true;
  insert into public.inspection_daily_stats (export_date, export_type_id, product_id, row_count, quantity_sum, weight_kg_sum)
  select d.export_date, d.export_type_id, d.product_id,
         count(*), coalesce(sum(d.quantity), 0), coalesce(sum(d.total_weight_kg), 0)
  from public.inspection_details d
  group by 1, 2, 3;
  get diagnostics v = row_count;
  return v;
end $$;

revoke all on function public.rebuild_inspection_daily_stats() from public, anon, authenticated;

select public.rebuild_inspection_daily_stats();

-- ---------- 6. RPC thống kê (đọc bảng tổng hợp; RLS theo người gọi) ----------
-- Tổng kg trong [p_from, p_to). Chữ ký và kết quả giữ nguyên như 000006.
create or replace function public.inspection_weight_total(p_from date, p_to date)
returns numeric
language sql stable security invoker set search_path = ''
as $$
  select coalesce(sum(weight_kg_sum), 0)
  from public.inspection_daily_stats
  where export_date >= p_from and export_date < p_to
$$;

-- p_group: 'export_type' | 'product' | 'month'. Khoảng [p_from, p_to); null = không giới hạn phía đó.
-- month: key_id = yyyymm (vd 202610), key_name = 'yyyy-mm'. Nhóm không có ngày/mục: key_id và key_name null.
create or replace function public.inspection_stats(p_from date, p_to date, p_group text)
returns table(key_id bigint, key_name text, row_count bigint, quantity_sum numeric, weight_kg_sum numeric)
language plpgsql stable security invoker set search_path = ''
as $$
#variable_conflict use_column
begin
  if p_group in ('export_type', 'product') then
    return query
    select g.kid, l.name, sum(g.row_count)::bigint, sum(g.quantity_sum), sum(g.weight_kg_sum)
    from (select case when p_group = 'export_type' then s.export_type_id else s.product_id end as kid,
                 s.row_count, s.quantity_sum, s.weight_kg_sum
          from public.inspection_daily_stats s
          where (p_from is null or s.export_date >= p_from) and (p_to is null or s.export_date < p_to)) g
    left join public.lookup_items l on l.id = g.kid
    group by g.kid, l.name
    order by l.name nulls last, g.kid;
  elsif p_group = 'month' then
    return query
    select (extract(year from g.m)::int * 100 + extract(month from g.m)::int)::bigint,
           to_char(g.m, 'YYYY-MM'), sum(g.row_count)::bigint, sum(g.quantity_sum), sum(g.weight_kg_sum)
    from (select date_trunc('month', s.export_date)::date as m,
                 s.row_count, s.quantity_sum, s.weight_kg_sum
          from public.inspection_daily_stats s
          where (p_from is null or s.export_date >= p_from) and (p_to is null or s.export_date < p_to)) g
    group by g.m
    order by g.m nulls last;
  else
    raise exception 'Nhóm thống kê không hợp lệ: %', p_group using errcode = '22023';
  end if;
end $$;

revoke all on function public.inspection_weight_total(date,date), public.inspection_stats(date,date,text) from public, anon;
grant execute on function public.inspection_weight_total(date,date), public.inspection_stats(date,date,text) to authenticated;

-- ---------- 7. Kiểm tra tính đúng ----------
do $$
declare i text;
begin
  assert (select coalesce(sum(weight_kg_sum), 0) from public.inspection_daily_stats)
       = (select coalesce(sum(total_weight_kg), 0) from public.inspection_details), 'tổng kg bảng tổng hợp lệch';
  assert (select coalesce(sum(quantity_sum), 0) from public.inspection_daily_stats)
       = (select coalesce(sum(quantity), 0) from public.inspection_details), 'tổng số lượng bảng tổng hợp lệch';
  assert (select coalesce(sum(row_count), 0) from public.inspection_daily_stats)
       = (select count(*) from public.inspection_details), 'tổng số dòng bảng tổng hợp lệch';
  assert exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
                 where n.nspname = 'public' and c.relname = 'inspection_daily_stats' and c.relrowsecurity), 'stats chưa bật RLS';
  assert (select count(*) from pg_policies where schemaname = 'public' and tablename = 'inspection_daily_stats') = 1, 'stats: phải có đúng 1 policy (select)';
  assert has_table_privilege('authenticated', 'public.inspection_daily_stats', 'select'), 'authenticated phải đọc được stats';
  assert not has_table_privilege('authenticated', 'public.inspection_daily_stats', 'insert')
     and not has_table_privilege('authenticated', 'public.inspection_daily_stats', 'update')
     and not has_table_privilege('authenticated', 'public.inspection_daily_stats', 'delete'), 'authenticated không được ghi stats';
  assert not has_table_privilege('anon', 'public.inspection_daily_stats', 'select'), 'anon không được đọc stats';
  assert (select count(*) from pg_trigger where tgrelid = 'public.inspection_details'::regclass
          and tgname like 'inspection_details_stats_%' and not tgisinternal) = 4, 'thiếu trigger tổng hợp';
  foreach i in array array[
    'public.search_plan_numbers(text,int)', 'public.search_lookup_items(text,text,int)', 'public.get_lookup_items(bigint[])',
    'public.inspection_weight_total(date,date)', 'public.inspection_stats(date,date,text)'
  ] loop
    assert to_regprocedure(i) is not null, 'thiếu hàm ' || i;
    assert has_function_privilege('authenticated', i, 'execute'), 'authenticated phải gọi được ' || i;
    assert not has_function_privilege('anon', i, 'execute'), 'anon không được gọi ' || i;
  end loop;
  foreach i in array array[
    'public.inspection_stats_apply()', 'public.inspection_stats_on_truncate()', 'public.rebuild_inspection_daily_stats()'
  ] loop
    assert not has_function_privilege('authenticated', i, 'execute'), 'authenticated không được gọi ' || i;
    assert not has_function_privilege('anon', i, 'execute'), 'anon không được gọi ' || i;
  end loop;
  foreach i in array array[
    'transport_plans_created_at_id_idx', 'transport_plans_export_date_id_idx', 'inspection_details_created_at_id_idx',
    'inspection_details_export_date_id_idx', 'lookup_items_kind_name_id_idx', 'inspection_daily_stats_key_uq'
  ] loop
    assert exists (select 1 from pg_indexes where schemaname = 'public' and indexname = i), 'thiếu index ' || i;
  end loop;
end $$;

commit;
