-- T-008 / D-007: đổi khóa chính + khóa ngoại từ uuid sang bigint identity, giữ nguyên dữ liệu.
-- Chuyển tại chỗ (không tạo lại bảng) nên RLS policy, grant, trigger, unique index (kind, lower(name)) và check giữ nguyên.
begin;

-- Số đếm trước khi chuyển, dùng cho phần kiểm tra cuối file
create temp table _mig_counts on commit drop as
select
  (select count(*) from public.lookup_items) as lookup_items,
  (select count(*) from public.transport_plans) as transport_plans,
  (select count(*) from public.transport_plan_material_exporters) as tpme,
  (select count(transport_type_id) + count(vehicle_id) + count(driver_id) + count(fg_exporter_id)
     from public.transport_plans) as plan_fks;

-- Hàm có chữ ký uuid: bỏ trước, tạo lại ở cuối
drop function public.create_transport_plan(date, text, uuid, uuid, uuid, uuid, uuid[], text);
drop function public.update_transport_plan(uuid, date, text, uuid, uuid, uuid, uuid, uuid[], text);

-- Bỏ khóa ngoại cũ (tạo lại cùng tên ở dưới)
alter table public.transport_plan_material_exporters
  drop constraint tpme_plan_id_fkey, drop constraint tpme_lookup_id_fkey;
alter table public.transport_plans
  drop constraint transport_plans_transport_type_id_fkey,
  drop constraint transport_plans_vehicle_id_fkey,
  drop constraint transport_plans_driver_id_fkey,
  drop constraint transport_plans_fg_exporter_id_fkey;

-- Giữ nguyên updated_at khi gán id mới
alter table public.lookup_items disable trigger lookup_items_set_updated_at;
alter table public.transport_plans disable trigger transport_plans_set_updated_at;

-- Đánh số mới
alter table public.lookup_items add column new_id bigint;
update public.lookup_items l set new_id = s.n
from (select id, row_number() over (order by created_at, kind, name) as n from public.lookup_items) s
where s.id = l.id;

alter table public.transport_plans add column new_id bigint,
  add column transport_type_id_n bigint, add column vehicle_id_n bigint,
  add column driver_id_n bigint, add column fg_exporter_id_n bigint;
update public.transport_plans p set new_id = s.n
from (select id, row_number() over (order by created_at) as n from public.transport_plans) s
where s.id = p.id;
update public.transport_plans p set
  transport_type_id_n = (select l.new_id from public.lookup_items l where l.id = p.transport_type_id),
  vehicle_id_n        = (select l.new_id from public.lookup_items l where l.id = p.vehicle_id),
  driver_id_n         = (select l.new_id from public.lookup_items l where l.id = p.driver_id),
  fg_exporter_id_n    = (select l.new_id from public.lookup_items l where l.id = p.fg_exporter_id);

alter table public.transport_plan_material_exporters add column plan_id_n bigint, add column lookup_id_n bigint;
update public.transport_plan_material_exporters t set
  plan_id_n   = (select p.new_id from public.transport_plans p where p.id = t.plan_id),
  lookup_id_n = (select l.new_id from public.lookup_items l where l.id = t.lookup_id);

-- Bỏ cột uuid (kéo theo PK và các index trên cột đó), đổi tên cột mới
alter table public.transport_plan_material_exporters drop column plan_id, drop column lookup_id;
alter table public.transport_plan_material_exporters rename column plan_id_n to plan_id;
alter table public.transport_plan_material_exporters rename column lookup_id_n to lookup_id;

alter table public.transport_plans
  drop column id, drop column transport_type_id, drop column vehicle_id, drop column driver_id, drop column fg_exporter_id;
alter table public.transport_plans rename column new_id to id;
alter table public.transport_plans rename column transport_type_id_n to transport_type_id;
alter table public.transport_plans rename column vehicle_id_n to vehicle_id;
alter table public.transport_plans rename column driver_id_n to driver_id;
alter table public.transport_plans rename column fg_exporter_id_n to fg_exporter_id;

alter table public.lookup_items drop column id;
alter table public.lookup_items rename column new_id to id;

alter table public.lookup_items alter column id set not null;
alter table public.lookup_items add primary key (id);
alter table public.lookup_items alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('public.lookup_items', 'id'),
  coalesce(max(id), 1), max(id) is not null) from public.lookup_items;

alter table public.transport_plans alter column id set not null;
alter table public.transport_plans add primary key (id);
alter table public.transport_plans alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('public.transport_plans', 'id'),
  coalesce(max(id), 1), max(id) is not null) from public.transport_plans;

-- Khóa ngoại + index (tên giữ như cũ, frontend embed theo tên)
alter table public.transport_plans
  add constraint transport_plans_transport_type_id_fkey foreign key (transport_type_id) references public.lookup_items(id) on delete restrict,
  add constraint transport_plans_vehicle_id_fkey foreign key (vehicle_id) references public.lookup_items(id) on delete restrict,
  add constraint transport_plans_driver_id_fkey foreign key (driver_id) references public.lookup_items(id) on delete restrict,
  add constraint transport_plans_fg_exporter_id_fkey foreign key (fg_exporter_id) references public.lookup_items(id) on delete restrict;
create index transport_plans_transport_type_id_idx on public.transport_plans (transport_type_id);
create index transport_plans_vehicle_id_idx on public.transport_plans (vehicle_id);
create index transport_plans_driver_id_idx on public.transport_plans (driver_id);
create index transport_plans_fg_exporter_id_idx on public.transport_plans (fg_exporter_id);

alter table public.transport_plan_material_exporters
  alter column plan_id set not null, alter column lookup_id set not null,
  add primary key (plan_id, lookup_id),
  add constraint tpme_plan_id_fkey foreign key (plan_id) references public.transport_plans(id) on delete cascade,
  add constraint tpme_lookup_id_fkey foreign key (lookup_id) references public.lookup_items(id) on delete restrict;
create index tpme_lookup_id_idx on public.transport_plan_material_exporters (lookup_id);

alter table public.lookup_items enable trigger lookup_items_set_updated_at;
alter table public.transport_plans enable trigger transport_plans_set_updated_at;

-- ---------- RPC (logic giữ nguyên, tham số đổi sang bigint) ----------
create function public.create_transport_plan(
  p_export_date date, p_transport_order_no text, p_transport_type_id bigint, p_vehicle_id bigint,
  p_driver_id bigint, p_fg_exporter_id bigint, p_material_exporter_ids bigint[], p_note text)
returns public.transport_plans language plpgsql set search_path = '' as $$
declare
  v_now timestamp := now() at time zone 'Asia/Ho_Chi_Minh';
  v_y int := extract(year from v_now)::int;
  v_m int := extract(month from v_now)::int;
  v_seq int;
  v_row public.transport_plans;
begin
  perform pg_advisory_xact_lock(hashtext('tk_number'));
  v_seq := public.tk_next_seq(v_y, v_m);
  if v_seq is null then
    raise exception 'Đã hết số phiếu thống kê trong tháng %/%', v_m, v_y using errcode = 'P0001';
  end if;

  insert into public.transport_plans (tk_number, tk_year, tk_month, tk_seq, export_date, transport_order_no,
    transport_type_id, vehicle_id, driver_id, fg_exporter_id, note)
  values (public.tk_format(v_y, v_m, v_seq), v_y, v_m, v_seq, p_export_date, nullif(btrim(p_transport_order_no), ''),
    p_transport_type_id, p_vehicle_id, p_driver_id, p_fg_exporter_id, nullif(btrim(p_note), ''))
  returning * into v_row;

  insert into public.transport_plan_material_exporters (plan_id, lookup_id)
  select distinct v_row.id, x from unnest(coalesce(p_material_exporter_ids, '{}')) x where x is not null;

  return v_row;
end $$;

create function public.update_transport_plan(
  p_id bigint, p_export_date date, p_transport_order_no text, p_transport_type_id bigint, p_vehicle_id bigint,
  p_driver_id bigint, p_fg_exporter_id bigint, p_material_exporter_ids bigint[], p_note text)
returns public.transport_plans language plpgsql set search_path = '' as $$
declare
  v_row public.transport_plans;
begin
  update public.transport_plans set
    export_date = p_export_date,
    transport_order_no = nullif(btrim(p_transport_order_no), ''),
    transport_type_id = p_transport_type_id,
    vehicle_id = p_vehicle_id,
    driver_id = p_driver_id,
    fg_exporter_id = p_fg_exporter_id,
    note = nullif(btrim(p_note), '')
  where id = p_id
  returning * into v_row;

  if not found then
    raise exception 'Không tìm thấy phiếu cần sửa' using errcode = 'P0002';
  end if;

  delete from public.transport_plan_material_exporters where plan_id = p_id;
  insert into public.transport_plan_material_exporters (plan_id, lookup_id)
  select distinct p_id, x from unnest(coalesce(p_material_exporter_ids, '{}')) x where x is not null;

  return v_row;
end $$;

revoke execute on function
  public.create_transport_plan(date,text,bigint,bigint,bigint,bigint,bigint[],text),
  public.update_transport_plan(bigint,date,text,bigint,bigint,bigint,bigint,bigint[],text)
  from public, anon;
grant execute on function
  public.create_transport_plan(date,text,bigint,bigint,bigint,bigint,bigint[],text),
  public.update_transport_plan(bigint,date,text,bigint,bigint,bigint,bigint,bigint[],text)
  to authenticated;

-- ---------- Kiểm tra (lỗi thì cả migration rollback) ----------
do $$
declare
  c record;
  v_seq text;
  v_last bigint;
  v_called boolean;
  v_max bigint;
begin
  select * into c from _mig_counts;
  assert (select count(*) from public.lookup_items) = c.lookup_items, 'lookup_items: số dòng thay đổi';
  assert (select count(*) from public.transport_plans) = c.transport_plans, 'transport_plans: số dòng thay đổi';
  assert (select count(*) from public.transport_plan_material_exporters) = c.tpme, 'tpme: số dòng thay đổi';
  assert (select count(transport_type_id) + count(vehicle_id) + count(driver_id) + count(fg_exporter_id)
          from public.transport_plans) = c.plan_fks, 'transport_plans: mất khóa ngoại';
  -- FK còn trỏ được (ràng buộc FK đã kiểm, kiểm lại bằng join)
  assert not exists (
    select 1 from public.transport_plans p
    where (p.transport_type_id is not null and not exists (select 1 from public.lookup_items l where l.id = p.transport_type_id))
       or (p.vehicle_id is not null and not exists (select 1 from public.lookup_items l where l.id = p.vehicle_id))
       or (p.driver_id is not null and not exists (select 1 from public.lookup_items l where l.id = p.driver_id))
       or (p.fg_exporter_id is not null and not exists (select 1 from public.lookup_items l where l.id = p.fg_exporter_id))
  ), 'transport_plans: khóa ngoại không trỏ được';

  -- sequence phải >= max(id) và đã "is_called" => nextval sẽ lớn hơn max(id)
  for v_seq, v_max in
    select pg_get_serial_sequence('public.lookup_items', 'id'), (select max(id) from public.lookup_items)
    union all
    select pg_get_serial_sequence('public.transport_plans', 'id'), (select max(id) from public.transport_plans)
  loop
    if v_max is not null then
      execute format('select last_value, is_called from %s', v_seq) into v_last, v_called;
      assert v_called and v_last >= v_max, format('sequence %s thấp hơn max(id)', v_seq);
    end if;
  end loop;
end $$;

commit;
